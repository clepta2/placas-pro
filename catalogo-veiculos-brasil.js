/**
 * Busca veículos no catálogo por termo livre (marca, modelo, segmento ou código FIPE).
 */
export function buscarVeiculosCatalogo(termo, { marca = null, categoria = null } = {}) {
  const q = String(termo || '').toLowerCase().trim();
  const m = String(marca || '').toLowerCase().trim();
  const c = String(categoria || '').toLowerCase().trim();

  return FAMILIAS_VEICULOS_BRASIL.filter(item => {
    if (m && item.marca.toLowerCase() !== m) return false;
    if (c && item.categoriaGeral !== c) return false;
    if (!q) return true;
    return item.nomeCompleto.toLowerCase().includes(q) ||
           item.modelo.toLowerCase().includes(q) ||
           item.marca.toLowerCase().includes(q) ||
           item.segmento.toLowerCase().includes(q) ||
           (item.fipe && item.fipe.codigo.includes(q));
  });
}

/**
 * Retorna todas as montadoras com metadados e contagem de modelos ativos.
 */
export function listarMontadorasComMetadados() {
  return MONTADORAS_BRASIL.map(mb => {
    const totalModelos = FAMILIAS_VEICULOS_BRASIL.filter(v => v.marca.toLowerCase() === mb.nome.split(' ')[0].toLowerCase()).length;
    return {
      ...mb,
      totalModelosCatalogados: totalModelos,
      logoUrl: `https://icons-pro-api.maputo2.workers.dev/api/icons/${mb.logoSlug}.svg`
    };
  });
}
